"""可复用的硬件 / 感知驱动层。

────────────────────────────────────────────────────────────────────────
这个目录放什么?

放 "不绑某一个 agent, 任何 agent 都可能用到" 的封装。典型例子:
  - 相机驱动 (RGBD / 普通 RGB / 事件相机)
  - 物体检测器 / 分割器 / 姿态估计器
  - 激光雷达、IMU、力传感器封装
  - TTS / ASR 客户端
  - 通用的几何工具函数 (位姿矩阵转换等)

这个目录默认是空的, 模板只搭好结构。等你接入硬件时再往里加文件。

────────────────────────────────────────────────────────────────────────
什么 *不* 放这里?

- 某一个 agent 的 prompt / tool schema / config         → agents/<name>/
- 某一个 agent 才用到的硬件 ID 或物理偏移               → agents/<name>/config.py
- LLM 工具调用循环、消息史管理                          → core/

判断标准: 如果未来写另一个 agent 也想直接复用, 才放 drivers/。
────────────────────────────────────────────────────────────────────────

加一个驱动的标准做法:

    1. 写 drivers/my_camera.py, 暴露一个类 (例如 MyCamera)
    2. 在本文件 __init__.py 加:  from .my_camera import MyCamera
    3. 在 __all__ 加:             "MyCamera"
    4. 在 agent 里:               from drivers import MyCamera
"""

